#!/usr/bin/env node
// The den-roles plugin: the den's roles for a target project's GitHub Actions, where `@claude <role>`
// starts one (claude-code-action with `plugins: den-roles@dimsumden-mods`). Role files only.
//   .claude/agents/<role>.md (ROLES) + scripts/den-roles-protocol.md -> plugins/den-roles/agents/<role>.md
// Each role keeps name, description, model, effort and color, and its tools minus the ones CI doesn't have
// (Agent(...), Skill, mcp__*, AskUserQuestion, Artifact). skills, isolation and org are dropped: the board
// skills would stop the role at its first claim. The body is the GitHub protocol, then the den role as reference.
// Usage: node scripts/den-roles-sync.mjs [--check] [--root <dir>]
//   write mode regenerates every role file and removes stale ones; --check writes nothing, prints each
//   drifted path and exits 1 on drift.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// The roles that make sense unattended on a pull request. The rest need the user, the board or the den.
export const ROLES = ["architect", "code-reviewer", "developer", "qa", "security", "technical-writer"];
const KEEP = ["name", "description", "tools", "model", "effort", "color"];
const DROP_TOOL = /^(Agent\(.*\)|Skill|AskUserQuestion|Artifact|mcp__.*)$/;

export const MANIFEST = {
  name: "den-roles",
  description: "Dim Sum Dev roles for a project's GitHub Actions: `@claude <role>` on a pull request runs that role. Generated by scripts/den-roles-sync.mjs.",
  version: "0.1.0",
};

// Top-level frontmatter keys -> raw value text (a nested block like org: stays one entry and is dropped).
function frontmatter(src) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/.exec(src);
  if (!m) throw new Error("role file has no frontmatter");
  const keys = {};
  let cur = null;
  for (const line of m[1].split(/\r?\n/)) {
    const k = /^([a-z][\w-]*):\s?(.*)$/.exec(line);
    if (k) keys[(cur = k[1])] = k[2];
    else if (cur) keys[cur] += `\n${line}`;
  }
  return { keys, body: m[2] };
}

export function renderRole(src, protocol) {
  const { keys, body } = frontmatter(src);
  const tools = keys.tools.split(/,\s*(?![^()]*\))/).map((t) => t.trim()).filter((t) => t && !DROP_TOOL.test(t));
  const head = KEEP.filter((k) => keys[k] !== undefined)
    .map((k) => `${k}: ${k === "tools" ? tools.join(", ") : keys[k]}`)
    .join("\n");
  return `---\n${head}\n---\n\n${protocol.trim()}\n\n## Your role in the den (reference: the board, handoff and den-command steps don't apply here)\n\n${body.trim()}\n`;
}

export function plan(root) {
  const protocol = readFileSync(path.join(root, "scripts", "den-roles-protocol.md"), "utf8");
  const out = new Map();
  const dir = path.join(root, "plugins", "den-roles");
  out.set(path.join(dir, ".claude-plugin", "plugin.json"), `${JSON.stringify(MANIFEST, null, 2)}\n`);
  for (const role of ROLES) {
    const src = readFileSync(path.join(root, ".claude", "agents", `${role}.md`), "utf8");
    out.set(path.join(dir, "agents", `${role}.md`), renderRole(src, protocol));
  }
  return out;
}

function run(argv) {
  const check = argv.includes("--check");
  const i = argv.indexOf("--root");
  const root = i >= 0 ? path.resolve(argv[i + 1]) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const want = plan(root);
  const agentsDir = path.join(root, "plugins", "den-roles", "agents");
  const stale = existsSync(agentsDir) ? readdirSync(agentsDir).map((f) => path.join(agentsDir, f)).filter((f) => !want.has(f)) : [];
  const drift = [...[...want].filter(([f, text]) => !existsSync(f) || readFileSync(f, "utf8") !== text).map(([f]) => f), ...stale];
  if (check) {
    for (const f of drift) console.log(`den-roles-sync: drifted ${path.relative(root, f)}`);
    if (drift.length) console.log("den-roles-sync: run `node scripts/den-roles-sync.mjs` and commit the result");
    process.exit(drift.length ? 1 : 0);
  }
  for (const [f, text] of want) {
    mkdirSync(path.dirname(f), { recursive: true });
    writeFileSync(f, text);
  }
  for (const f of stale) rmSync(f);
  console.log(`den-roles-sync: wrote ${want.size} files${stale.length ? `, removed ${stale.length}` : ""}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) run(process.argv.slice(2));
