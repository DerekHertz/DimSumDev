import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { makeBridge, until, send } from '../agents/host-test-helpers.mjs';

test('independent takes and source-linked follow-ups come from their own host runs; answers create no work', { timeout: 20000 }, async t => {
  const b = await makeBridge(); t.after(() => b.close());
  const started = await b.post('/meetings', { topic: 'Choose a recovery strategy', roles: ['architect', 'qa'], budget: 8 });
  assert.equal(started.status, 201, started.text);
  const id = started.body.meeting.id;
  const spawn = n => until(() => b.fake.spawns[n], { what: `run ${n}` });
  const say = async (n, text) => { const rec = await spawn(n); rec.emit({ type: 'reply', text }); rec.emit({ type: 'done', ok: true, costUsd: 0.1 }); };
  const get = async () => (await send(b.bridge, { path: `/meetings/${id}`, headers: b.headers })).body;
  await say(0, 'Claim: Use one journal\nEvidence: storage.mjs\nConfidence: fairly sure');
  const qa = await spawn(1);
  assert.equal((await readFile(path.join(qa.args.cwd, '.den/meeting.md'), 'utf8')).includes('Use one journal'), false, 'opening views are independent');
  await say(1, 'Claim: Partition for recovery\nEvidence: recovery.mjs\nConfidence: unsure');
  const source = (await get()).events.find(e => e.actor === 'architect' && e.kind === 'message');
  await say(2, JSON.stringify({ action: 'follow-up', requests: [{ role: 'qa', sourceId: source.id, instruction: 'Respond to the journal claim', effort: 'medium' }] }));
  const response = await spawn(3);
  assert.equal(response.args.role, 'qa');
  assert.match(await readFile(path.join(response.args.cwd, '.den/meeting.md'), 'utf8'), /Use one journal/);
  await say(3, 'Claim: A single journal can recover safely');
  const reply = await until(async () => (await get()).events.find(e => e.text === 'Claim: A single journal can recover safely'), { what: 'attributed linked response' });
  assert.equal(reply.actor, 'qa'); assert.equal(reply.sourceId, source.id);
  assert.notEqual(reply.runId, source.runId);
  await say(4, JSON.stringify({ action: 'decision', question: 'One journal?', options: [{ key: 'A', title: 'One', tradeoff: 'Simple, but grows' }, { key: 'B', title: 'Many', tradeoff: 'Small, but dispersed' }], recommended: 'A', required: ['architect', 'qa'], sourceIds: [source.id, reply.id] }));
  await until(async () => (await b.state()).meetings[0].state === 'waiting-decision', { what: 'user decision' });
  const before = (await b.state()).tickets.length;
  assert.equal((await b.post(`/meetings/${id}/decide`, { text: 'Use one, with recovery tests' })).status, 202);
  assert.equal((await b.state()).tickets.length, before);
  const answered = await get();
  assert.equal(answered.meeting.questions[0].answer.text, 'Use one, with recovery tests');
  assert.equal(answered.events.find(e => e.kind === 'decision-answer').questionId, answered.meeting.questions[0].id);
  const privateFile = path.join(b.fx.root, '.scratch/_run/meetings.jsonl');
  assert.equal((await stat(privateFile)).mode & 0o777, 0o600);
  assert.equal(execFileSync('git', ['-C', b.fx.root, 'ls-files', '.scratch'], { encoding: 'utf8' }), '');
});

test('permanent ended records replay through an actual bridge restart, and reading starts no work', { timeout: 20000 }, async t => {
  const first = await makeBridge(); t.after(() => first.fx.cleanup());
  const started = await first.post('/meetings', { topic: 'Permanent record', roles: ['architect'], budget: 0, project: 'den' });
  const id = started.body.meeting.id;
  await until(async () => (await first.state()).meetings[0].state === 'waiting-budget', { what: 'budget wait' });
  await first.post(`/meetings/${id}/close`);
  const record = (await send(first.bridge, { path: `/meetings/${id}`, headers: first.headers })).body;
  await first.bridge.close();
  const file = path.join(first.fx.root, '.scratch/_run/meetings.jsonl');
  const raw = await readFile(file, 'utf8');
  const lines = raw.trim().split('\n').map(line => { const row = JSON.parse(line); row.meeting.updatedAt = '2020-01-01T00:00:00Z'; return JSON.stringify(row); });
  await writeFile(file, lines.join('\n') + '\n');
  const second = await makeBridge({ root: first.fx.root }); t.after(() => second.bridge.close());
  const replayed = (await send(second.bridge, { path: `/meetings/${id}`, headers: second.headers })).body;
  assert.equal(replayed.meeting.state, 'ended'); assert.equal(replayed.meeting.project, 'den');
  assert.deepEqual(replayed.events, record.events);
  assert.equal(second.fake.spawns.length, 0);
  assert.equal((await second.post(`/meetings/${id}/resume`)).status, 409);
});
